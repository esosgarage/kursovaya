/*
* Файл содержит реализацию математической логики:
* расчет функции по трем ветвям в зависимости от x
*/

#include "math_proc.h"

/* --- Приватные функции --- */

/* проверяет, входит ли x в область определения */
static int is_defined(double x);

/* --- Определение функций --- */

/* * проверяет допустимость значения x
* x - аргумент функции
* возвращает 1, так как согласно заданию функция определена везде
*/
static int is_defined(double x) {
	/* согласно формуле, деление на (x-1) происходит только при x < 1 */
	return 1;
}

/* * рассчитывает значение f(x) согласно трем ветвям
* x - входное значение
* ptr_ok - флаг успешного выполнения
*/
double calc_func(double x, int* ptr_ok) {
	double sum;
	int n;

	*ptr_ok = 1;

	if (!is_defined(x)) {
		*ptr_ok = 0;
		return 0.0;
	}

	if (x < -1) {
		/* ветвь 1: гиперболический синус */
		return sinh(x);
	}
	else if (x < 1) {
		/* ветвь 2: дробно-рациональная функция */
		/* x >= -1 подразумевается структурой else-if */
		return (pow(x, 3) - 1) / (x - 1);
	}
	else {
		/* ветвь 3: сумма ряда от 0 до 11 при x >= 1 */
		sum = 0.0;
		for (n = 0; n <= 11; n++) {
			sum += (pow(-1, n) * pow(x, n)) / sqrt(pow(n, 2) + 4);
		}
		return sum;
	}
}
